    fun getJuzForPage(page: Int): Int {
        var juz = 1
        for (i in 1..30) {
            val startP = paraStartPages[i] ?: 1
            if (page >= startP) {
                juz = i
            }
        }
        return juz
    }

    fun getSurahForPage(page: Int): Surah {
        var currentSurah = surahList.first()
        for (surah in surahList) {
            if (page >= surah.startPage) {
                currentSurah = surah
            } else {
                break
            }
        }
        return currentSurah
    }

    suspend fun fetchPageData(pageNumber: Int): QuranPageData = withContext(Dispatchers.IO) {
        val juz = getJuzForPage(pageNumber)
        val surah = getSurahForPage(pageNumber)

        try {
            val urlString = "https://api.alquran.cloud/v1/page/$pageNumber/quran-uthmani"
            val conn = URL(urlString).openConnection() as HttpURLConnection
            conn.connectTimeout = 5000
            conn.readTimeout = 5000
            conn.requestMethod = "GET"

            if (conn.responseCode == 200) {
                val jsonStr = conn.inputStream.bufferedReader().use { it.readText() }
                val root = JSONObject(jsonStr)
                val dataObj = root.getJSONObject("data")
                val ayahsArray = dataObj.getJSONArray("ayahs")

                val fullTextBuilder = StringBuilder()
                for (i in 0 until ayahsArray.length()) {
                    val ayahObj = ayahsArray.getJSONObject(i)
                    val text = ayahObj.getString("text")
                    val numInSurah = ayahObj.getInt("numberInSurah")
                    fullTextBuilder.append(text).append(" ﴿").append(toArabicNumber(numInSurah)).append("﴾ ")
                }

                // Chunk text into page lines
                val combinedText = fullTextBuilder.toString().trim()
                val words = combinedText.split(" ")
                val lines = mutableListOf<String>()
                val wordsPerLine = Math.max(1, (words.size + 14) / 15)

                for (i in 0 until 15) {
                    val start = i * wordsPerLine
                    if (start < words.size) {
                        val end = Math.min(start + wordsPerLine, words.size)
                        lines.add(words.subList(start, end).joinToString(" "))
                    }
                }

                if (lines.isNotEmpty()) {
                    return@withContext QuranPageData(
                        pageNumber = pageNumber,
                        juzNumber = juz,
                        surahName = "সুরা ${surah.nameBangla} (${surah.nameArabic})",
                        lines = lines
                    )
                }
            }
        } catch (e: Exception) {
            e.printStackTrace()
        }

        // Offline fallback lines if network request fails
        val fallbackLines = List(15) { lineIdx ->
            "بِسْمِ اللَّهِ الرَّحْمَٰنِ الرَّحِيمِ ﴿${toArabicNumber(lineIdx + 1)}﴾ - [صفحة $pageNumber - سورة ${surah.nameArabic}]"
        }

        return@withContext QuranPageData(
            pageNumber = pageNumber,
            juzNumber = juz,
            surahName = "সুরা ${surah.nameBangla} (${surah.nameArabic})",
            lines = fallbackLines
        )
    }

    private fun toArabicNumber(num: Int): String {
        val arabicDigits = charArrayOf('٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩')
        val str = num.toString()
        val sb = StringBuilder()
        for (ch in str) {
            if (ch.isDigit()) {
                sb.append(arabicDigits[ch - '0'])
            } else {
                sb.append(ch)
            }
        }
        return sb.toString()
    }
